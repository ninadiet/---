def _replace_quotes_alternating(text: str, char: str, open_q: str, close_q: str) -> str:
    """半角クォートを開閉交互置換する（1個目→開き括弧、2個目→閉じ括弧、...）"""
    parts = text.split(char)
    result = parts[0]
    for i, part in enumerate(parts[1:]):
        result += open_q if i % 2 == 0 else close_q
        result += part
    return result


def sanitize_post_text(text: str) -> str:
    """投稿テキストから禁止文字を除去・変換する（最終防衛線）"""
    # ── ツリー区切りの正規化（2026-08-05 追加・アフィリ側 writer.py と同じ穴の横展開）──
    # 後段（ron_post.py / ron_scheduled_post.py / restore_tree_history.py）は
    # "===THREAD===" の完全一致で分割している。生成AIが稀に末尾の "===" を落とすと
    # 分割されず複数投稿が1つに合体する（アフィリ側で実測：2回中1回発生）。
    text = re.sub(r'^[ \t]*=+[ \t]*THREAD[ \t]*=*[ \t]*$', '===THREAD===',
                  text, flags=re.MULTILINE)
    # ⚠️ 2026-09-09 全面差し替え：以前は **強調** を「」に変換していたが、
    #   これは「「」は感情と会話だけ」という確定ルールと正面から矛盾する。
    #   さらに **「子どもの月齢」** のように既に括られた語を囲むと
    #   「「子どもの月齢」」 と**二重括弧**になる（実測で投稿本文に出た）。
    #   ③の writer.py は最初から「カッコは増やさない」実装だったので、そちらに揃える。
    text = re.sub(r'\*\*(.+?)\*\*', r'\1', text)
    text = text.replace('*', '')
    # ダブルクオート類は削除（カッコに変換しない）
    for _q in ['"', '“', '”', '＂']:
        text = text.replace(_q, '')
    for _q in ['‘', '’', "''"]:
        text = text.replace(_q, '')
    # 二重括弧の畳み込み（保険）
    text = text.replace('「「', '「').replace('」」', '」')
    return text

def force_opening_line(text: str, opening: str) -> str:
    """各SLOTの1投稿目冒頭に定番つかみを強制挿入する"""
    lines = text.split("\n")
    result_lines = []
    in_slot = False
    slot_first_line_done = False

    for line in lines:
        stripped = line.strip()
        # SLOT開始を検知（━━━の罫線の後）
        if "━━━" in stripped:
            if not in_slot:
                in_slot = True
                slot_first_line_done = False
            else:
                # 2つ目の罫線 = SLOT終了
                in_slot = False
            result_lines.append(line)
            continue

        # SLOT内の最初の非空行にopening_lineを挿入
        if in_slot and not slot_first_line_done and stripped:
            slot_first_line_done = True
            if opening not in stripped:
                result_lines.append(opening)
            result_lines.append(line)
            continue

        result_lines.append(line)

    return "\n".join(result_lines)


