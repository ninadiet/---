def load_my_material() -> str:
    """素材帳（operation/my_material.md）を読む。2026-09-01 新設。

    なぜ在るか：2026-08-24 に「実体験バンク」（運営自身の体験が固定で書かれていた）を
    撤去したが、**オーナー自身の素材を置く場所を作らなかった**。その結果、
    ルーナが使える素材は「声定義（自己紹介）」「テーマファイル（運用方針）」
    「直近の自分の投稿（＝AIが書いた話）」だけになり、一方でプロンプトは
    「固有名詞と具体的数字を必ず入れろ」と要求していた。
    素材ゼロ＋具体を出せという命令＝**創作**になり、
    「平均的にありそうな話」「測っていない数字」が生成される構造だった（実アカで実測）。

    ここは体験に限定しない。①体験 ②手の内（指示文・手順） ③視点 の3種類を受け付ける。
    ノウハウ主体のアカウントは②だけでも具体的な投稿が作れるため。
    空でも運用は止めない（従来どおり動く）。"""
    try:
        with open(MY_MATERIAL_PATH, "r", encoding="utf-8") as f:
            body = f.read()
    except OSError:
        return ""
    # 見出し・説明文・記入例（「（例）」で始まる行）を落として、実記入だけを残す。
    # 記入例をそのまま素材として渡すと、例文が投稿に出てしまう（〇〇 の事故と同じ型）。
    lines = []
    for ln in body.splitlines():
        t = ln.strip()
        if not t or t.startswith(("#", ">", "-" * 3, "|")):
            continue
        if t.startswith(("- （例）", "-（例）", "（例）", "* （例）")):
            continue
        if t.startswith("⚠"):
            continue
        lines.append(t)
    text = chr(10).join(lines).strip()
    return text if len(text) >= 10 else ""


def load_theme_directives(cli_theme: str = "") -> str:
    """本日のテーマ指定を集める（2026-08-01 追加）。

    それまでテーマは hermione_research.py にしか渡っておらず、
    ルーナ（執筆）には一切届いていなかった。そのため theme に
    「◯◯は書かない」と明記しても本文に混入し続けた。
    ここで2経路を拾う：
      1. ワークフローから渡される --theme（workflow_dispatch の入力）
      2. operation/themes/ の最新ファイル（番号が大きいものを最新とみなす）
    """
    parts = []
    t = (cli_theme or "").strip()
    if t and t.lower() not in ("none", "null"):
        parts.append(f"【本日のテーマ指定】\n{t}")

    themes_dir = os.path.join(SCRIPT_DIR, "..", "operation", "themes")
    try:
        files = sorted(f for f in os.listdir(themes_dir) if f.endswith(".md"))
        if files:
            path = os.path.join(themes_dir, files[-1])
            with open(path, "r", encoding="utf-8") as f:
                body = f.read()
            body = _strip_operator_notes(body)
            if body:
                parts.append(f"【テーマファイル {files[-1]}】\n{body}")
    except Exception as e:
        logger.warning(f"テーマファイルの読み込みをスキップ: {e}")

    return "\n\n".join(parts)


def _strip_operator_notes(md: str) -> str:
    """テーマファイルから「人間向けの説明」を落として、AIへの指示だけ残す。

    ⚠️ 2026-08-05 追加（実測で発覚）：テーマファイルを丸ごとプロンプトに入れていたため、
    「このフォルダの最新ファイルが読まれます」「2026-08-01 改訂」といった**運用の説明**まで
    AIが読み、テーマ指定と食い違うと判断して
    **投稿ではなく『緊急報告：指示の矛盾について』という報告文を返す**事故が起きた。
    3本生成して2本が壊れた（もう1本はテーマ枠をそのまま本文に転記）。

    落とすもの：引用行（>）＝注意書き、「テーマファイルの書き方」以降＝運営向け手順、
    見出しの ⚠️ 行。残すのは投稿の方向性・必須要素・避ける角度だけ。
    """
    out = []
    for line in md.splitlines():
        s = line.strip()
        if s.startswith(">"):            # 引用＝人間向けの注意書き
            continue
        if s.startswith("⚠️") or s.startswith("※"):
            continue
        if s.startswith("## テーマファイルの書き方"):  # ここから下は運営向け手順
            break
        out.append(line)
    return "\n".join(out).strip()


