    persona_name = extract_persona_name(voice_def)
    opening_line = extract_opening_line(voice_def)
    voice_suffixes = extract_voice_suffixes(voice_def)
    # ── 丁寧語（です・ます）の扱い（2026-09-07 本人裁定で全面変更）──────────
    # 旧実装は「です・ます」を**無条件で使用禁止**にしていた。その結果、
    # 語尾を書いていない顧客は全員フランク口調（だよ・んだ）へ強制的に誘導され、
    # 「顧客が違うのにトンマナが同じ」の直接原因になっていた。
    # 本人裁定＝「顧客指定があればそれを最優先。無ければ です・ます が通常の語尾」。
    #   ・指定あり  → その語尾だけを使う（です・ます系でも、フランクでも、方言でも従う）
    #   ・指定なし  → です・ます を基本に、キャラ設定に合わせて整える（禁止しない）
    # ⚠️ 校閲側（malfoy_review.py）と必ず同じ判断にすること。片方だけ変えると
    #    書く側と直す側が噛み合わず、毎日差し戻し→投稿ゼロになる。
    if voice_suffixes:
        polite_rule = ("- 丁寧語（です・ます）: 上の「語尾」の指定が最優先。"
                       "指定に無い語尾は、丁寧語・フランクを問わず使わない")
    else:
        polite_rule = ("- 丁寧語（です・ます）: 声定義に語尾の指定が無いので、"
                       "**「です・ます」を基本の語尾として使ってよい**。"
                       "上のキャラクター設定に合う範囲で整えること")

    # KV外出しの追加ルール（無ければ空＝従来と同一のプロンプト）
    _rules = load_prompt_rules()
    rule_extra = (_rules["追加ルール"] + chr(10) * 2) if _rules["追加ルール"] else ""

    # ── 2026-08-24 追加（顧客報告への根本対応）────────────────────────
    # ここまで、執筆担当が読むのは声定義とプロンプトルールの2つだけだった。
    # そのため「昨日なにを書いたか」を知らず、同じ題材を数日おきに繰り返していた。
    # また、オーナーが自分で足したルールファイルは誰も読んでいなかった。
    # 検査で弾くだけだと毎日差し戻しになるので、**書く前に渡す**。
    # ── 今日の「型」を選ぶ（2026-08-25 追加・型の勝ち残りゲーム）────────
    # 自分の成績上位2型＋探索枠1型。採点が溜まるまでは全型を均等に試す。
