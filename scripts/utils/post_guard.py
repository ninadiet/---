FORMAT_RETRY_NOTE = (
    "⛔ 直前の出力は**形式が壊れていました**（スロットの見出しが出ていない）。"
    "内容の方針は変えなくてよいので、**形だけ**必ず守って書き直してください。\n"
    "・出力の1文字目は `🌅 SLOT_1【` から始める\n"
    "・SLOT_1 / SLOT_2 / SLOT_3 の3つを、1回の出力で全部書く\n"
    "・各SLOTの投稿の区切りは `===THREAD===` の行だけを使う\n"
    "・前置き・あいさつ・説明を書かない\n"
)


# ── 出力が薄すぎたら、その場で1回だけ書き直す（2026-09-12 追加・③④共通）
# なぜ在るか：
#   本人指摘「文字数が少なすぎて無駄にツリー移動しすぎではないか」。実測すると
#   1投稿40字前後×5投稿＝1日600字まで痩せた日があった（読者は40字ごとにタップする）。
#
#   原因を4回追って、4回とも外した。順に「ストックに理由が無い」「膨らませる指示が足りない」
#   「型が1項目1行と言っている」「①②③を投稿ごとに分けている」──全部プロンプト側を疑ったが、
#   55→40→41→44 と1ミリも動かなかった。
#
#   切り分けで分かった本当の原因＝**その日どのモデルが答えたか**。
#     ・同じプロンプト・同じ日で gemini-3-flash-preview は中央46字、
#       gemini-flash-latest は中央31字（1.5倍の差）
#     ・同じプロンプトを人（強いモデル）が書くと中央101字・1日1,172字で、目標どおり出る
#   ＝ 指示は足りている。**弱いモデルに落ちた日だけ痩せる。**
#
#   プロンプトをどれだけ磨いても「弱いモデルの日」は消せない。だから
#   形式の自動修復（本番で3回発火・3回とも修復）と同じ形で、**薄さも機械で直す**。
#
# ⚠️ 良い日は1文字も動かない（追加の呼び出しは発生しない）。薄い日だけ1回多く呼ぶ。
# ⚠️ 作り直しは1回だけ。直らなければそのまま校閲へ渡す（投稿を止めない）。
# ⚠️ しきい値は実測の谷で決めた：良い日は中央98〜134字、薄い日は31〜55字。
#    間の70字を境にすれば、良い日を巻き込まない。

#: 本文（フックと締めを除いた中間の投稿）の中央字数がこれを下回ったら「薄い」
THIN_MEDIAN = 70


def _body_lengths(text: str) -> list:
    """各SLOTの「2投稿目〜最後の1つ手前」の字数を集める（フックと締めは短くて当然なので外す）。"""
    out = []
    for m in _SLOT_HEAD_RX.finditer(text or ""):
        start = m.end()
        nxt = _SLOT_HEAD_RX.search(text, start)
        body = text[start: nxt.start() if nxt else len(text)]
        parts = [p.strip().strip("━").strip()
                 for p in re.split(r"\n?===\s*THREAD\s*===\n?", body)]
        parts = [p for p in parts if p]
        if len(parts) >= 3:
            out += [len(p) for p in parts[1:-1]]
    return out


def thin_output_reason(text: str) -> str:
    """薄すぎるなら理由を返す（問題なければ空文字）。"""
    lens = _body_lengths(text)
    if len(lens) < 3:            # 測れるだけの本文が無い日は判定しない
        return ""
    lens.sort()
    med = lens[len(lens) // 2]
    if med >= THIN_MEDIAN:
        return ""
    return "本文の中央が%d字しかありません（目安100〜250字）" % med


