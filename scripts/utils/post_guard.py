# -*- coding: utf-8 -*-
"""post_guard.py — 「投稿してはいけないテキスト」を判定する唯一の場所（2026-09-01 新設）

なぜ在るか
──────────────────────────────────────────────────────────
実際の利用者アカウントで、**投稿本文として `（SLOT_3 抽出失敗）` がそのまま公開された**。
同じ日に `🌆 SLOT_2【18時・夕方投稿】` という**見出し行まで本文に混ざって公開**された。

原因の連鎖：
  ① 校閲が投稿案からスロット本文を抽出できないと、承認申請コメントに
     `（SLOT_N 抽出失敗）` という文字列を**そのまま書き込んでいた**
  ② 投稿スクリプトはそれを本文として受け取り、そのまま投稿した
  ③ アフィリのキットには②を止める検査（is_placeholder）があったが、
     **ホグのキットには一度も移植されていなかった**（同じ検査が2つのキットで
     別々に書かれ、片方だけ育っていた）

なので「検査をもう1つ足す」のではなく、**判定を1か所に集約する**。
以後、投稿する経路はすべてこの関数だけを見る。片方だけ直る事故を構造的になくす。
"""
import re

# 投稿されたら事故になる文字列（機械が作った内部マーカー・雛形の残骸）
_INTERNAL_MARKERS = [
    "抽出失敗",        # 校閲がスロット本文を取り出せなかった時の内部表記
    "（SLOT_", "(SLOT_",  # 同上（かっこ付きの形）
    "投稿内容なし",   # 旧テンプレの「ここに本題」は下の雛形行判定で弾く
]

# 見出し行そのもの（Issueの表示用であって本文ではない）
_HEADING_RX = re.compile(
    r"(?m)^\s*(?:[🌅🌆🌙📋📤🎩🖋️]|SLOT_[123]\s*[【\[]|\*\*🌅|\*\*🌆|\*\*🌙)"
)
# 区切り線（Issue整形用の飾り。本文に入ることはない）
_BAR_RX = re.compile(r"[━]{5,}")

# TODO は「書きかけの印」の形のときだけ弾く（2026-09-08）
# ⚠️ 以前は文中の "TODO" を無条件に弾いていたが、実測で
#    「この議事録からタスクを抽出してと指示すれば、TODOリストまで作ってくれる」
#    という**ごく普通の本文**が差し戻された（AIの使い方を書くジャンルでは毎日起きる）。
#    印としての TODO は必ずコロンか括弧を伴うか、1行で独立している。
_TODO_RX = re.compile(r"(?m)TODO\s*[:：]|[\[<{]TODO[\]>}]|^[ 	　\-*・]*TODO[ 	　]*$")

# 角括弧だけで1行が完結している行＝出力フォーマットの雛形行（2026-09-08 追加）
# 実測：各SLOTの本文の1行目にあたる
#   「[この後に本題のフックを続ける。合計40〜90字が目安]」
#   「[2投稿目：本文・導入]」
# が、_INTERNAL_MARKERS にも _PLACEHOLDER_RX にも当たらず、
# unpostable_reason() は None（＝投稿可）を返していた。
# ⚠️ 語を足して塞ぐと、テンプレの文言を変えた次の日にまた同じ穴が開く
#    （上の「見出し語を列挙して弾く」で一度やった失敗と同じ）。
#    なので中身の語は一切見ず、「角括弧で始まって角括弧で終わる行」という形だけで弾く。
#    本文で使う括弧は「」『』（）【】なので、この形が自然文として出ることはない。
_TEMPLATE_LINE_RX = re.compile(r"(?m)^[ \t\u3000]*[\[［][^\]］\n]{4,}[\]］][ \t\u3000]*$")

# ── プロンプトの指示行が本文に混ざるパターン（2026-09-07 追加・同日作り直し）
# 実測：投稿本文の冒頭に、執筆プロンプト側にしか無いはずの
#   「※ <見出し語>：<指示>」という指示行が**そのまま公開された**（4回中1回）。
# その回は区切り線が出なかったので既存の検査は全部素通りし、
# unpostable_reason() は None（＝投稿可）を返していた。
# 2026-09-01 に塞いだ「見出し行が公開された」のと同じ経路
# （＝本文の外に書いたはずの機械の文字が、本文として運ばれる）。
#
# ⚠️ 最初の実装は「プロンプトに出てくる見出し語」を列挙して弾いていた。これは弱い：
#   ・プロンプトの文言を変えるたびにこの列挙も直さないと素通りする
#     （＝「同じ検査が2か所にあり片方だけ直る」のと同じ失敗を、今度は1ファイル内で繰り返す）
#   ・見出し語には日常語も混じるので、本文で普通に使っただけで差し戻しになる
# そこで**語を数えるのをやめ、行の「形」で見る**。
#   プロンプトの指示行は「※ <短いラベル>：<中身>」という**ラベル＋コロン**の形をとる。
#   一方、本文に自然に出る注釈（「※ 個人差があります」「※ 字数の都合で省略しました」）は
#   コロンをとらない。コロンをとる自然な注釈は数が限られるので、
#   **列挙するのを「本文に出てよい方」に反転させる**（下の許可リスト）。
# こうすると、プロンプト側に新しい見出しが増えてもここを直さずに捕まえられる。
_NOTE_LINE_RX = re.compile("(?m)^[ \t\u3000]*※[^\n]*")
# 「※ <ラベル>：」の形。ラベルは短く、文末記号を含まない（＝文章ではなく見出し）
_LABELED_NOTE_RX = re.compile(
    "^[ \t\u3000]*※[ \t\u3000]*"
    "(?P<label>[^\n：:。．！？!?]{1,24})"
    "[ \t\u3000]*[：:]"
)
# 本文に出てよい注釈ラベル（これだけは「※ ○○：」でも通す）
_NATURAL_NOTE_LABELS = (
    "注", "注意", "補足", "追記", "訂正", "免責", "出典", "参考", "引用",
    "PR", "AD", "広告", "宣伝", "対象", "価格", "期間", "締切", "定員",
    "まとめ", "結論", "ポイント",
)
# 機械側の内部トークン（コロンが無くてもこれが混ざっていれば指示行）
_MACHINE_TOKENS = ("SLOT", "THREAD", "===", "{", "}")
_PAREN_RX = re.compile("[（(][^）)]*[）)]")


def _is_prompt_instruction(line: str) -> bool:
    """※で始まる1行が「執筆プロンプト側の指示行」かを、語ではなく形で判定する"""
    if any(t in line for t in _MACHINE_TOKENS):
        return True
    m = _LABELED_NOTE_RX.match(line)
    if not m:
        return False
    # 「見出し（言い換え）：」のように補足がついていても、本体だけを見る
    label = _PAREN_RX.sub("", m.group("label")).strip(" \t\u3000・-—")
    return label not in _NATURAL_NOTE_LABELS


# 未置換のプレースホルダ（リンク・雛形変数）
_PLACEHOLDER_RX = re.compile(
    r"\[[^\]]*(?:アフィリ|リンク|ここに|URL|貼る|挿入)[^\]]*\]"
    r"|\{\{[^}]{1,40}\}\}"
    # ⚠️ 2026-09-09 追加：**一重の波括弧**。③のプロンプトには
    #   「{良かれと思ってやってたことが裏目に出る系の気づき文}」のような雛形があり、
    #   二重波括弧だけ見ていた旧実装では素通りした。
    #   日本語の本文で { } を使うことはまず無いので、中身が日本語なら雛形と見なす。
    r"|\{[^{}\n]{2,60}\}"
)

# ── 伏せ字（〇〇 / △△ / ××）の扱い（2026-09-08 作り直し）
# 旧実装は伏せ字を見つけたら無条件で弾いていた。ところが実測7日×3ジャンルで、
# AIの使い方を書くジャンルが**7日中3日、計5本**を差し戻されていた。中身は
#   「〇〇の件で、△△さんに依頼のメールを書きたい」と、ゴールをはっきり伝える
# のような、**読者に見せるための穴埋め例文**。これは消し忘れではなく本題そのもの。
# 差し戻しが続けば投稿ゼロに倒れる（過去に丁寧語の利用者で実際に起きている）。
#
# 消し忘れと例文は、次の2点で分かれる：
#   (1) 例文は「」『』の中にある（読者に見せる引用だから括る）
#   (2) 消し忘れは「〇〇（商品名や特徴）」のように**何を入れるかの但し書き**が付く
# よって「括弧の外の伏せ字」と「但し書き付きの伏せ字」だけを弾く。
# ⚠️ 伏せ字の丸は3種類ある：〇(U+3007 漢数字ゼロ)・○(U+25CB)・◯(U+25EF 大きい丸)。
#    見た目がほぼ同じなのにコード点が違うので、一つでも抜けるとそこだけ素通りする。
#    実際、プロンプト内の「最新の◯◯」は U+25EF だった（2026-09-08 発見）。
#    三角・バツも同じ理由で対を揃える。
_MASK_CHARS = "〇○◯△▲▽▼×✕✖"
_MASK_RX = re.compile(r"[〇○◯]{2,}|[△▲▽▼]{2,}|[×✕✖]{2,}")
_MASK_LABELED_RX = re.compile(
    r"(?:[〇○◯]{2,}|[△▲▽▼]{2,}|[×✕✖]{2,})\s*[（(][^）)]{0,24}[）)]")
_QUOTED_RX = re.compile(r"[「『][^」』]{0,300}[」』]")
# ── 集団の割合主張（2026-09-09 追加・③④共通）
# 例：「9割のママが」「約95%が悩みが軽くなったと答えている」「利用率は65.1%」
#
# なぜ弾くか
#   CLAUDE.md が「緩和しない例外」として名指ししている2つのうちの1つ。
#   ③はアフィリがあるので景表法・薬機法に直結する。④も、根拠の弱い割合は
#   読者の信頼を直接損なう（数字が大きいほど「本当？」になる）。
#
# ⚠️ 2026-09-09 に実測で発覚した経緯：
#   出典のサイト名を本文に書かせない方針にした直後、生成が
#   「ある調査によると、育児の不安が軽くなったと感じる人は約95%」
#   のような**出所をぼかした割合主張**を出すようになった（199本中15本）。
#   社名を書いていた時より悪い。読者が検証する手がかりが消えるからで、
#   これは「ぼかす」方針そのものの副作用。だから**割合だけは例外**にして、
#   ぼかした状態では書かせない。
#
#   同じ199本のうち、素材帳が埋まっている条件では**割合主張はゼロ**だった。
#   ＝素材が無いとモデルは調査の数字に手を伸ばす。根本の対策は素材帳を埋めること。
#
# 何を弾き、何を通すか
#   弾く：割合（%・割）が**人の集団**に掛かっているもの
#         「◯%の人が」「◯割のママが」「◯%が〜と答えた／感じている」「利用率は◯%」
#   通す：モノ・量の割合（「電池が20%」「10分の1」「3割引」「湿度60%」）
#         公的機関を明記したもの（「厚生労働省の調査では◯%」）＝出所が検証できる
_RATIO_TOKEN = r"(?:\d{1,3}(?:\.\d+)?\s*[%％]|[0-9０-９一二三四五六七八九十]\s*割)"
#: 人の集団を指す語（この近くに割合があれば集団割合主張とみなす）
_GROUP_WORDS = (r"人|方|ママ|パパ|親|保護者|母|父|家庭|世帯|ユーザー|利用者|"
                r"みんな|みなさん|読者|子|子ども|子供|女性|男性|会社員|主婦")
#: 調査の言い回し（「〜が答えている」「〜と感じている」）
_SURVEY_VERBS = r"答え|回答|感じ|思っ|考え|利用し|使っ|経験"
_RATIO_GROUP_RX = re.compile(
    # ①「◯%の人が」型 … 割合 → (の)? → 集団語
    r"(?:" + _RATIO_TOKEN + r")\s*(?:の|に|は|も|が)?\s*(?:" + _GROUP_WORDS + r")"
    # ②「人の◯%が」型 … 集団語 → 〜 → 割合
    r"|(?:" + _GROUP_WORDS + r")[^。\n]{0,12}(?:" + _RATIO_TOKEN + r")"
    # ③「利用率は◯%」「◯%が答えている」型 … 割合 → 〜 → 調査の動詞
    r"|(?:" + _RATIO_TOKEN + r")[^。\n]{0,20}(?:" + _SURVEY_VERBS + r")"
    r"|(?:率|割合)[^。\n]{0,8}(?:" + _RATIO_TOKEN + r")"
)
#: 出所が検証できる公的機関。ここを本文に明記していれば通す（読者が確かめられる）
_PUBLIC_SOURCES = (
    "消費者庁", "厚生労働省", "厚労省", "総務省", "経済産業省", "経産省", "文部科学省",
    "文科省", "内閣府", "国民生活センター", "国立", "統計局", "こども家庭庁", "WHO",
)


MIN_LEN = 10


def unpostable_reason(text: str):
    """投稿してはいけない理由を返す（問題なければ None）。

    ⚠️ ここは**全文**を見る。以前は先頭200字だけを見ており、
       投稿末尾に残ったプレースホルダが公開された事故が起きている。
    """
    body = text or ""
    if len(body.strip()) < MIN_LEN:
        return "本文が短すぎます（抽出に失敗している可能性）"
    for m in _INTERNAL_MARKERS:
        if m in body:
            return "内部マーカー「%s」が本文に残っています（校閲が本文を取り出せていません）" % m
    m = _TODO_RX.search(body)
    if m:
        return "書きかけの印（TODO）が本文に残っています（%s）" % m.group().strip()[:20]
    m = _HEADING_RX.search(body)
    if m:
        line = body[m.start():].split("\n", 1)[0][:40]
        return "見出し行が本文に混ざっています（…%s…）" % line.strip()
    if _BAR_RX.search(body):
        return "区切り線（━）が本文に混ざっています"
    m = _TEMPLATE_LINE_RX.search(body)
    if m:
        return "出力フォーマットの雛形行が本文に残っています（%s）" % m.group().strip()[:40]
    for _line in _NOTE_LINE_RX.findall(body):
        if _is_prompt_instruction(_line):
            return "プロンプトの指示行が本文に混ざっています（%s…）" % _line.strip()[:40]
    m = _PLACEHOLDER_RX.search(body)
    if m:
        return "未置換のプレースホルダが残っています（%s）" % m.group()[:40]
    m = _MASK_LABELED_RX.search(body)
    if m:
        return "雛形の伏せ字が残っています（%s）" % m.group()[:40]
    # 「」『』の中は読者に見せる例文なので、そこの伏せ字は消し忘れではない
    m = _MASK_RX.search(_QUOTED_RX.sub("", body))
    if m:
        return "未置換の伏せ字が残っています（%s）" % m.group()[:40]
    # 集団の割合主張。公的機関を本文に明記していれば通す（読者が確かめられるため）。
    if not any(w in body for w in _PUBLIC_SOURCES):
        m = _RATIO_GROUP_RX.search(body)
        if m:
            return ("集団の割合を出所なしで書いています（%s）。"
                    "公的機関名を明記するか、数字を落として手順の具体さで書くこと" % m.group()[:30])
    return None


def is_placeholder(text: str) -> bool:
    """後方互換：従来の真偽値インターフェース"""
    return unpostable_reason(text) is not None

# ── 生成直後に使う「プロンプトの写し」落とし（2026-09-07 追加）
# 上の _is_prompt_instruction() は「行の形」で見るが、それでも取りこぼす形はある
#  （例：「※ 投稿の順序が正しいことを確認（フック→本文→…→CTA）」＝コロンも機械語も無い）。
# ただし生成した直後なら、**実際に送った文面そのもの**が手元にある。
# そこで「送った※行と一字一句同じ行が出力に出ていたら落とす」を先に通す。
# 語を1つも列挙しないので、プロンプトを書き換えてもここを直す必要がない。
#
# ⚠️ 対象を「※で始まる行」だけに絞る理由：
#   ===THREAD=== / 区切り線 / SLOT見出し / 定番つかみ もプロンプトに載っているが、
#   これらは本文の抽出に使う（消すと逆に「抽出失敗」を作る）。
#   ※行はプロンプト側の宣言で「本文に1文字も出さない」と決めてあるので、
#   消しても本文が壊れない唯一の種類。
_ECHO_HEAD_RX = re.compile("^[ \t　]*[-*・>#]*[ \t　]*")


def _echo_key(line: str) -> str:
    return _ECHO_HEAD_RX.sub("", line).strip().replace(" ", "").replace("　", "")


def strip_prompt_echo(text: str, prompt: str) -> str:
    """出力に紛れ込んだ「送ったプロンプトの※行そのもの」を取り除く"""
    if not text or not prompt:
        return text
    sent = set()
    for ln in prompt.split("\n"):
        k = _echo_key(ln)
        if k.startswith("※") and len(k) >= 8:
            sent.add(k)
    if not sent:
        return text
    kept = []
    for ln in text.split("\n"):
        k = _echo_key(ln)
        if k.startswith("※") and k in sent:
            continue
        kept.append(ln)
    return "\n".join(kept)


# ── 最終投稿の締め方を機械で見る（2026-09-10 追加・同日作り直し・③④共通）
# なぜ在るか：
#   「最終投稿には必ずCTAを入れる」はプロンプトに以前から書いてあったが、
#   実測（21スロット×3ジャンル）では **①21本中12本・②9本がCTA無しで終わっていた**。
#   文章で指示するだけでは守られない。ここは機械が正確に見られる。
#
# ⚠️ 最初の実装は語尾が丁寧語（「なります」「届けています」）の形しか登録しておらず、
#    方言・カジュアル体の利用者を**全部差し戻していた**（実測：②は21本中20本が不合格）。
#      「AI活用術を発信してるよ」  → CTAとして拾えない
#      「毎日の献立決めがもっと楽になる」→ 未来として拾えない
#    語尾で判定してはいけない。**語幹で見る**。
#    これを見落とすと、方言の顧客だけ毎日差し戻されて投稿ゼロになる（過去の事故と同型）。
#
# ⚠️ 判定は「両方無いとき」だけ差し戻す。片方あれば通す。
#    本人の指示＝「CTAがないか、それか未来への期待で締められないか」＝**どちらかでよい**。
#    両方を必須にすると差し戻しが増えすぎて投稿ゼロ側に倒れる。
#
# ⚠️ これは「投稿してはいけない」ではなく「締め方が弱い」判定なので、
#    unpostable_reason() には入れない（投稿経路を止める話ではない）。校閲が差し戻しに使う。

#: 「何を届けているか／どこへ来てほしいか」の語幹（活用形はすべて拾う）
_CTA_STEMS = (
    "フォロー", "プロフ", "発信", "シェア", "届け", "配信", "紹介", "投稿して",
    "受け取", "覗い", "のぞい", "見に来", "見てみ", "見てね", "チェック",
    "保存", "お待ち", "ご覧", "更新して", "また来", "まとめてる", "まとめています",
)
#: 「読者がどうなるか」＝未来の語幹
_FUTURE_STEMS = (
    "楽に", "ラクに", "らくに", "減ら", "減る", "減っ", "変わ", "なくな",
    "落ち着", "スッキリ", "すっきり", "ゆとり", "余裕", "助か", "軽くな", "軽減",
    "できるよう", "迷わ", "防げ", "防ぎ", "済む", "済み", "短く", "早く",
    "生まれ", "手に入", "自由に", "使えるよう", "分かるよう", "わかるよう",
)


def cta_shortfall(last_part: str) -> str:
    """最終投稿の締め方が弱いときに理由を返す（問題なければ空文字）。

    Args:
        last_part: そのスロットの**最後の投稿**の本文
    """
    t = (last_part or "").strip()
    if not t:
        return ""
    has_cta = any(w in t for w in _CTA_STEMS)
    has_future = any(w in t for w in _FUTURE_STEMS)
    if has_cta or has_future:
        return ""
    return ("最終投稿が感想で終わっています。"
            "「読者がどうなるか」か「何を届けているか」のどちらかを必ず入れてください")


# ── 出力の形式が壊れていたら、その場で1回だけ作り直す（2026-09-11 追加・③④共通）
# なぜ在るか：
#   実測で「SLOT見出しを1つも出さず、1本の記事として書く」日が 7〜20日に1回出た。
#   これまではそのまま校閲へ渡り、抽出できず差し戻し → その日の投稿が作れなかった。
#   本人判断：**形式無視は許容できない**。
#
#   起きる条件はほぼ1つで、**モデル連鎖が gemini-2.5-flash-lite に落ちた日**。
#   lite系が投稿フォーマットを守らないのは gemini_model_chain.txt に既知として記録がある。
#   flash の1日の枠を使い切った日にここへ落ちる。
#
# ⚠️ 差し戻し（校閲まで往復）ではなく**書き手の中で完結**させる。
#    往復すると再生成の上限に当たり「その日の投稿が出ない」事故になる（実測2回）。
# ⚠️ 作り直しは**1回だけ**。無限に投げ続けない（枠を焼き切らないため）。

_SLOT_HEAD_RX = re.compile(r"(?m)^(?!\s*[-+・>]).*SLOT[_ ]?([123])\s*[【\[]")


def format_broken_reason(text: str, need_slots: int = 3) -> str:
    """出力の形式が壊れているなら理由を返す（問題なければ空文字）。

    見るのは「投稿が作れる形か」だけ。中身の良し悪しは見ない。
    """
    t = text or ""
    found = set(_SLOT_HEAD_RX.findall(t))
    missing = [str(i) for i in range(1, need_slots + 1) if str(i) not in found]
    if missing:
        return "SLOT_%s の見出しが出力にありません" % "・".join(missing)
    if "===THREAD===" not in t:
        return "ツリーの区切り（===THREAD===）が1つもありません"
    return ""


